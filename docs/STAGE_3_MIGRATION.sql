-- Stage 3: reservations. Applied to Supabase project hnbyqcohznceoefmzzpl.
-- The public catalog remains readable. Only signed-in users can reserve/cancel.
create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id bigint not null references public.books(id),
  copy_id bigint not null references public.copies(id),
  status text not null default 'active' check (status in ('active','cancelled')),
  created_at timestamptz not null default now(),
  cancelled_at timestamptz
);
create unique index if not exists reservations_active_copy_uniq on public.reservations(copy_id) where status='active';
create unique index if not exists reservations_active_user_book_uniq on public.reservations(user_id,book_id) where status='active';
create index if not exists reservations_user_id_idx on public.reservations(user_id,created_at desc);
alter table public.reservations enable row level security;
revoke all on public.reservations from public,anon,authenticated;
grant select on public.reservations to authenticated;
create policy "Users read only own reservations" on public.reservations
  for select to authenticated using ((select auth.uid())=user_id);

create or replace function public.reserve_book(p_book_id bigint)
returns bigint language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid(); v_copy bigint; v_res_id bigint;
begin
  if v_user is null or coalesce((auth.jwt()->>'is_anonymous')::boolean,false) then
    raise exception 'Sign in before reserving' using errcode='42501';
  end if;
  if p_book_id is null or not exists(select 1 from public.books where id=p_book_id) then
    raise exception 'Unknown book' using errcode='22023';
  end if;
  -- Algorithm: serialize reservations for a book, select the available copy
  -- with the smallest ID, lock it, then reserve atomically.
  perform pg_advisory_xact_lock(64231,p_book_id::integer);
  if exists(select 1 from public.reservations where user_id=v_user and book_id=p_book_id and status='active') then
    raise exception 'Already reserved by this account' using errcode='23505';
  end if;
  select id into v_copy from public.copies
    where book_id=p_book_id and status='available'
    order by id asc limit 1 for update;
  if v_copy is null then raise exception 'No available copies' using errcode='P0001'; end if;
  update public.copies set status='reserved' where id=v_copy;
  insert into public.reservations(user_id,book_id,copy_id)
    values(v_user,p_book_id,v_copy) returning id into v_res_id;
  return v_res_id;
end $$;

create or replace function public.cancel_my_reservation(p_reservation_id bigint)
returns boolean language plpgsql security definer set search_path=''
as $$
declare v_user uuid:=auth.uid(); v_copy bigint;
begin
  if v_user is null or coalesce((auth.jwt()->>'is_anonymous')::boolean,false) then
    raise exception 'Sign in before cancelling' using errcode='42501';
  end if;
  select copy_id into v_copy from public.reservations
    where id=p_reservation_id and user_id=v_user and status='active'
    for update;
  if v_copy is null then raise exception 'Reservation not found' using errcode='P0002'; end if;
  update public.reservations set status='cancelled',cancelled_at=now()
    where id=p_reservation_id;
  update public.copies set status='available' where id=v_copy and status='reserved';
  return true;
end $$;
revoke all on function public.reserve_book(bigint) from public,anon;
revoke all on function public.cancel_my_reservation(bigint) from public,anon;
grant execute on function public.reserve_book(bigint),public.cancel_my_reservation(bigint) to authenticated;

-- Stage 3 full CRUD: only owners can DELETE their previously cancelled rows.
-- This is a real DELETE, unlike cancellation (UPDATE / soft-delete).
grant delete on public.reservations to authenticated;
create policy "Users delete own cancelled reservations" on public.reservations
for delete to authenticated
using ((select auth.uid())=user_id and status='cancelled');
