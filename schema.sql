-- Verify the records
SELECT
    b.id,
    b.title_bg,
    g.name_bg AS genre,
    COUNT(c.id) AS total_copies,
    COUNT(c.id) FILTER (
        WHERE c.status = 'available'
    ) AS available_copies
FROM public.books b
JOIN public.genres g ON g.id = b.genre_id
LEFT JOIN public.copies c ON c.book_id = b.id
GROUP BY b.id, b.title_bg, g.name_bg
ORDER BY b.id;
