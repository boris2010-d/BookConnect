
-- BookConnect — Stage 2
-- Database schema and sample data

-- 1. Genres
CREATE TABLE public.genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_bg TEXT NOT NULL,
    name_en TEXT NOT NULL,
    code TEXT NOT NULL UNIQUE
);

-- 2. Books
CREATE TABLE public.books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    genre_id BIGINT NOT NULL REFERENCES public.genres(id),
    title_bg TEXT NOT NULL,
    title_en TEXT NOT NULL,
    author_bg TEXT NOT NULL,
    author_en TEXT NOT NULL,
    description_bg TEXT,
    description_en TEXT,
    cover_url TEXT
);

-- 3. Physical copies of books
CREATE TABLE public.copies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES public.books(id),
    inventory_number TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'available',
    CONSTRAINT copies_status_check
        CHECK (status IN ('available', 'borrowed', 'reserved'))
);

-- Enable Row Level Security
ALTER TABLE public.genres ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.books ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.copies ENABLE ROW LEVEL SECURITY;

-- Public read access for the catalog
CREATE POLICY "Public can read genres"
ON public.genres
FOR SELECT TO anon, authenticated
USING (true);

CREATE POLICY "Public can read books"
ON public.books
FOR SELECT TO anon, authenticated
USING (true);

CREATE POLICY "Public can read copies"
ON public.copies
FOR SELECT TO anon, authenticated
USING (true);

-- No public INSERT, UPDATE or DELETE policies.
-- Data management will be added later with authentication.

